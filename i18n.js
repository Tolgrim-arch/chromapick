let currentLang = localStorage.getItem('chromapick_lang') || navigator.language.split('-')[0];
if (!translations[currentLang]) {
    currentLang = 'en';
}

function changeLanguage(lang) {
    if (!translations[lang]) return;
    currentLang = lang;
    localStorage.setItem('chromapick_lang', lang);
    document.documentElement.lang = lang;
    applyTranslations();
    if (window.renderPalettes) window.renderPalettes();
    if (window.renderCombinations) window.renderCombinations();
}

function applyTranslations() {
    const dict = translations[currentLang];
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            if (el.tagName.toLowerCase() === 'input' && el.type === 'button') {
                el.value = dict[key];
            } else {
                el.innerHTML = dict[key]; // innerHTML allows <strong> tags in dropzone
            }
        }
    });

    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if (dict[key]) {
            el.title = dict[key];
        }
    });
    
    // Update raw text nodes if needed (like the "Pick from screen" buttons which have SVG icons)
    document.querySelectorAll('.btn-pick-text').forEach(el => {
        el.textContent = dict['pick_screen'];
    });
}

// Init when DOM is loaded
window.addEventListener('DOMContentLoaded', () => {
    applyTranslations();
    const langSelect = document.getElementById('lang-select');
    if (langSelect) {
        langSelect.value = currentLang;
        langSelect.addEventListener('change', (e) => {
            changeLanguage(e.target.value);
        });
    }
});

window.translations = translations;
